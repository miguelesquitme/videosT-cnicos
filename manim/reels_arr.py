class ReelArr(ReelV2):
    def setup(self):
        super().setup()
        reel_v2.Pieza.CARPETA = EQ

    def pz(self, n, ancho=None, alto=None, pos=(0, -1.5)):
        """Piezas grandes: centradas ×1,28 (y un poco más abajo), en pareja ×1,12; nunca más de 8,6 × 9,4."""
        solo = abs(pos[0]) < 0.05
        f = 1.28 if solo else 1.12
        p = Pieza(n, ancho * f if ancho else None, alto * f if alto else None)
        if p.width > 8.6:
            p.scale_to_fit_width(8.6)
        if p.height > 9.4:
            p.scale_to_fit_height(9.4)
        p.move_to([pos[0], pos[1] - (0.5 if solo else 0.3), 0])
        return p

    def poner(self, nueva, vieja=None):
        if vieja is not None and hasattr(nueva, "k") and hasattr(vieja, "img"):
            f = vieja.img.width / nueva.img.width
            nueva.scale(f)
            nueva.k *= f
        return super().poner(nueva, vieja)

    def cerrar(self, *mobs):
        self.cerrar_voz(0.05)
        self.wait(1.4)
        self.limpiar(*mobs)

    def fl(self, txt, punto, desde, i=0, size=24):
        return self.flecha(txt, punto, desde, self.ac(i), size)

    def diag(self, alto=9.4, centro=(0, -1.6)):
        H = diagrama_mando(alto=alto, centro=centro)
        g = H.todo()
        panel = RoundedRectangle(width=g.width + 0.5, height=g.height + 0.4, corner_radius=0.12, stroke_width=0).set_fill(BL, 1).move_to(g)
        return H, VGroup(panel, g)

    def mk(self, H, tr, i=1):
        return H.marca(tr, self.ac(i), 10, 0.9)

    def gira(self, mo, vel=16.0):
        e = eje_girando(mo, vel)
        self.add(e)
        return e


def _portada(scene, preg, pieza, alto, sticker_txt, color="#FF4D6D"):
    reel_v2.Pieza.CARPETA = EQ
    pz = Pieza(pieza, alto=alto * 1.4)
    if pz.width > 8.6:
        pz.scale_to_fit_width(8.6)
    if pz.height > 6.8:
        pz.scale_to_fit_height(6.8)
    portada_v(scene, preg, pz, sticker_txt, color)


