"""V22 v2 · Toques al tocar metal: estática vs fuga. Piezas: lib/svgv22.py → v22v2_eq/. Guion: guion_v22v2.py."""
from reel_v2 import *  # noqa: F401,F403


class V22v2(ReelV2):
    CLAVE = "v22v2"
    GUION_MOD = "guion_v22v2"

    def cuerpo(self):
        C, Am, G, Rr, Vi = self.ac(0), self.ac(1), self.ac(2), self.ac(3), self.ac(4)
        GR = "#5B6472"

        # ------------------------------------------------------------ gancho
        self.voz("gancho")
        mj = Pieza("manija", 8.4).move_to([0, 1.55, 0])
        self.play(FadeIn(mj), run_time=0.5)
        self.en("toque")
        mjc = Pieza("manija_chispa", 8.4)
        self.sfx("disparo", -16)
        self.poner(mjc, mj)
        self.play(Flash(mjc.p("yema"), color="#BDEBFF", flash_radius=0.5), run_time=0.35)
        self.en("lavadora")
        lv = Pieza("lavadora", alto=4.6).move_to([0, -3.9, 0])
        self.play(FadeIn(lv, shift=UP * 0.2), run_time=0.45)
        self.en("inofensivo")
        t1 = self.nota("inofensivo", G, [2.6, -0.5, 0], 30)
        self.play(FadeIn(t1, scale=1.2), run_time=0.3)
        self.en("matarte")
        t2 = self.nota("puede matarte", Rr, [2.7, -3.0, 0], 30)
        mr = self.recuadro(lv.img.get_center(), lv.img.width + 0.1, lv.img.height + 0.1, Rr)
        self.play(FadeIn(t2, scale=1.2), Create(mr), run_time=0.35)
        self.cerrar(mjc, lv, t1, t2, mr)

        # ------------------------------------------------------------ p1 estática
        self.voz("p1")
        self.chip("1", "ESTÁTICA", C)
        mj = Pieza("manija", 8.4).move_to([0, 1.55, 0])
        self.play(FadeIn(mj), run_time=0.4)
        self.en("alfombra")
        ax, g = self.ejes([0.3, -3.3, 0], 7.0, 3.0, (0, 4), (0, 40), "", "kV")
        b1 = Rectangle(width=1.4, height=ax.c2p(0, 35)[1] - ax.c2p(0, 0)[1], stroke_width=0).set_fill(Am, 1)
        b1.move_to(ax.c2p(1.1, 0), aligned_edge=DOWN)
        b2 = Rectangle(width=1.4, height=ax.c2p(0, 1.5)[1] - ax.c2p(0, 0)[1], stroke_width=0).set_fill(C, 1)
        b2.move_to(ax.c2p(2.9, 0), aligned_edge=DOWN)
        l1 = T("10–25 %", 22, self.th["txt2"], "BOLD").next_to(b1, DOWN, buff=0.1)
        l2 = T("65–90 %", 22, self.th["txt2"], "BOLD").next_to(b2, DOWN, buff=0.1)
        l1 = VGroup(l1, T("humedad relativa del aire", 22, self.th["txt2"], "BOLD").move_to(ax.c2p(2, 0) + DOWN * 0.75))
        self.play(Create(ax), FadeIn(g), run_time=0.4)
        self.en("35|treinta")
        v1 = self.nota("35 000 V", Am, b1.get_top() + UP * 0.32, 28)
        self.play(GrowFromEdge(b1, DOWN), FadeIn(l1), FadeIn(v1), run_time=0.5)
        self.en("1500|mil")
        v2 = self.nota("1 500 V", C, b2.get_top() + UP * 0.32, 28)
        self.play(GrowFromEdge(b2, DOWN), FadeIn(l2), FadeIn(v2), run_time=0.45)
        self.en("acercar")
        mjc = Pieza("manija_chispa", 8.4)
        self.en("chispa")
        self.sfx("disparo", -14)
        self.poner(mjc, mj)
        self.play(Flash(mjc.p("yema"), color="#BDEBFF", flash_radius=0.6), run_time=0.4)
        self.cerrar(mjc, ax, g, b1, b2, l1, l2, v1, v2)

        # ------------------------------------------------------------ p2 energía (IEC 61000-4-2)
        self.voz("p2")
        self.chip("2", "LA ENERGÍA DE LA CHISPA", Am)
        self.en("capacitor")
        cap = VGroup(Line(LEFT * 0.5, RIGHT * 0.5), Line(LEFT * 0.5, RIGHT * 0.5).shift(DOWN * 0.22)).set_stroke(self.th["txt"], 6)
        res = Rectangle(width=0.36, height=1.0, stroke_color=self.th["txt"], stroke_width=5)
        mod = VGroup(cap, res).arrange(RIGHT, buff=1.6).move_to([0, 2.2, 0])
        ct, cb, rt_, rb = cap[0].get_center(), cap[1].get_center(), res.get_top(), res.get_bottom()
        yt, yb = ct[1] + 0.55, cb[1] - 0.55
        w1 = VMobject().set_points_as_corners([ct, [ct[0], yt, 0], [rt_[0], yt, 0], rt_]).set_stroke(self.th["txt"], 5)
        w2 = VMobject().set_points_as_corners([cb, [cb[0], yb, 0], [rb[0], yb, 0], rb]).set_stroke(self.th["txt"], 5)
        tc = T("150 pF", 26, Am, "HEAVY").next_to(cap, LEFT, buff=0.25)
        tr = T("330 Ω", 26, Am, "HEAVY").next_to(res, RIGHT, buff=0.25)
        tmod = T("modelo del cuerpo · IEC 61000-4-2", 22, self.th["txt2"], "BOLD").move_to([0, 3.4, 0])
        self.play(FadeIn(mod), Create(w1), Create(w2), FadeIn(tc), FadeIn(tr), FadeIn(tmod), run_time=0.6)
        self.en("8000|ocho")
        ax, g = self.ejes([0.3, -1.6, 0], 7.4, 4.0, (0, 100), (0, 35), "tiempo (ns)", "A")
        pts = [(0, 0), (0.8, 30), (2.5, 15), (8, 12.5), (20, 14.5), (30, 16), (45, 12), (60, 8), (80, 4), (100, 1.5)]
        xs = np.linspace(0, 100, 400)
        ys = np.interp(xs, [p[0] for p in pts], [p[1] for p in pts])
        cur = VMobject().set_points_smoothly([ax.c2p(x, y) for x, y in zip(xs[::4], ys[::4])]).set_stroke(Am, 6)
        self.play(Create(ax), FadeIn(g), run_time=0.4)
        self.en("pico")
        self.play(Create(cur), run_time=1.2)
        d1 = Dot(ax.c2p(0.8, 30), radius=0.1, color=Rr)
        n1 = self.nota("30 A en 0,8 ns", Rr, ax.c2p(30, 31), 24)
        self.play(FadeIn(d1, scale=1.5), FadeIn(n1), run_time=0.3)
        self.en("60|sesenta")
        d2 = Dot(ax.c2p(60, 8), radius=0.1, color=C)
        n2 = self.nota("8 A a 60 ns", C, ax.c2p(72, 17), 24)
        self.play(FadeIn(d2, scale=1.5), FadeIn(n2), run_time=0.3)
        self.en("energía")
        e = self.card("ENERGÍA ≈ 5 mJ", ["½·C·V² = ½ · 150 pF · (8 kV)²"], G, 7.8, 28).move_to([0, -4.9, 0])
        self.play(FadeIn(e, shift=UP * 0.15), run_time=0.4)
        self.en("1000|mil")
        n3 = self.nota("< 1 000 V: casi nadie la siente", GR, [0, -6.4, 0], 24)
        self.play(FadeIn(n3), run_time=0.3)
        self.cerrar(mod, w1, w2, tc, tr, tmod, ax, g, cur, d1, n1, d2, n2, e, n3)

        # ------------------------------------------------------------ p3 la fuga
        self.voz("p3")
        self.chip("3", "LA FUGA", Rr)
        lv = Pieza("lavadora", alto=5.2).move_to([-2.0, 0.4, 0])
        fs = Pieza("falla_sin", 5.4).move_to([1.4, -4.2, 0])
        self.play(FadeIn(lv), run_time=0.4)
        self.en("cable")
        lnk = Line(lv.p("cordon"), fs.img.get_top() + LEFT * 0.3).set_stroke(C, 3)
        self.play(FadeIn(fs, shift=UP * 0.2), Create(lnk), run_time=0.45)
        self.en("rosó|rozó")
        ar = self.aro(fs.p("falla"), 0.4, Am)
        self.play(Create(ar), run_time=0.3)
        self.en("peló")
        fc = Pieza("falla_chispa", 5.4)
        self.sfx("disparo", -16)
        self.poner(fc, fs)
        nf = self.nota("fase pelada contra el chasis", Am, [1.4, -1.25, 0], 22)
        self.play(FadeIn(nf), run_time=0.3)
        self.en("tierra")
        nt = self.nota("sin conductor de tierra", GR, [1.4, -6.9, 0], 22)
        self.play(FadeIn(nt), run_time=0.3)
        self.en("120|ciento")
        mr = self.recuadro(lv.img.get_center(), lv.img.width + 0.1, lv.img.height + 0.1, Rr)
        v = self.nota("chasis a 120 V", Rr, [2.4, 2.4, 0], 28)
        self.play(Create(mr), FadeIn(v, scale=1.2), run_time=0.4)
        self.en("hormigueo")
        hz = self.nota("hormigueo que se repite", Rr, [2.4, 1.6, 0], 22)
        self.play(FadeIn(hz), Indicate(mr, color=Rr), run_time=0.5)
        self.cerrar(lv, fc, lnk, ar, nf, nt, mr, v, hz)

        # ------------------------------------------------------------ p4 la corriente
        self.voz("p4")
        self.chip("4", "LA CORRIENTE", Am)
        ax, g = self.ejes([0.3, 2.0, 0], 7.4, 2.4, (0, 50), (-1.2, 1.2), "tiempo (ms)", "")
        seno = ax.plot(lambda t: np.sin(2 * PI * 60 * t / 1000), x_range=[0, 50, 0.1], color=Rr, stroke_width=5)
        self.play(Create(ax), FadeIn(g), run_time=0.3)
        self.en("60|sesenta")
        nh = self.nota("60 ciclos por segundo, sin parar", Rr, [0, 3.55, 0], 22)
        self.play(Create(seno), FadeIn(nh), run_time=1.0)
        self.en("seca")
        c1 = self.card("PIEL SECA ≈ 100 000 Ω", ["120 V ÷ 100 kΩ = 1,2 mA"], C, 7.8, 28).move_to([0, -0.9, 0])
        self.play(FadeIn(c1, shift=UP * 0.15), run_time=0.4)
        self.en("mojada")
        c2 = self.card("PIEL MOJADA ≈ 1 000 Ω", ["120 V ÷ 1 kΩ = 120 mA"], Rr, 7.8, 28).move_to([0, -2.85, 0])
        self.play(FadeIn(c2, shift=UP * 0.15), run_time=0.4)
        self.en("6|seis")
        c3 = self.card("6 a 16 mA", ["ya no te puedes soltar (OSHA)"], Am, 7.8, 28).move_to([0, -4.8, 0])
        self.play(FadeIn(c3, shift=UP * 0.15), run_time=0.4)
        self.cerrar(ax, g, seno, nh, c1, c2, c3)

        # ------------------------------------------------------------ p5 la tierra
        self.voz("p5")
        self.chip("5", "LA PATA DE TIERRA", G)
        cl = Pieza("clavija_lado", 8.4).move_to([0, 2.0, 0])
        self.play(FadeIn(cl), run_time=0.4)
        self.en("redonda")
        ar = self.aro(cl.p("pata_tierra"), 0.38, G)
        self.play(Create(ar), run_time=0.3)
        self.en("larga")
        x1, x2 = cl.p("punta_plana")[0], cl.p("punta_tierra")[0]
        yb = cl.p("pata_tierra")[1] - 0.45
        br = VGroup(Line([x1, yb + 0.6, 0], [x1, yb, 0]), Line([x2, yb + 0.2, 0], [x2, yb, 0]), Line([x1, yb, 0], [x2, yb, 0])).set_stroke(Am, 4)
        nl = self.nota("3,2 mm más larga", Am, [x2 - 1.4, yb - 0.4, 0], 22)
        self.play(Create(br), FadeIn(nl), run_time=0.35)
        self.en("chasis")
        ft = Pieza("falla_tierra", 5.6).move_to([-0.9, -3.3, 0])
        self.play(FadeIn(ft, shift=UP * 0.2), run_time=0.45)
        self.en("verde")
        av = self.aro(ft.p("tierra"), 0.38, G)
        self.play(Create(av), run_time=0.3)
        bk = Pieza("brk_on", alto=2.9).move_to([3.4, -3.3, 0])
        self.play(FadeIn(bk), run_time=0.3)
        self.en("dispara")
        bo = Pieza("brk_off", alto=2.9)
        self.sfx("disparo", -10)
        self.poner(bo, bk)
        nd = self.nota("se dispara", Rr, [3.4, -5.15, 0], 24)
        self.play(FadeIn(nd), run_time=0.25)
        self.en("cortes")
        cs = Pieza("clavija_sin_tierra", 1.7).move_to([-2.6, -6.2, 0])
        xx = VGroup(Line(UL, DR), Line(UR, DL)).scale(0.55).set_stroke(Rr, 8).move_to(cs)
        nn = self.nota("nunca le cortes la pata", Rr, [0.8, -6.2, 0], 24)
        self.play(FadeIn(cs), Create(xx), FadeIn(nn), run_time=0.4)
        self.cerrar(cl, ar, br, nl, ft, av, bo, nd, cs, xx, nn)

        # ------------------------------------------------------------ p6 en campo
        self.voz("p6")
        self.chip("6", "EN CAMPO", C)
        mm0 = Pieza("mm_0", alto=4.4).move_to([0, 1.3, 0])
        lv = Pieza("lavadora", alto=4.0).move_to([-2.5, -4.1, 0])
        tm = Pieza("tomacorriente", alto=3.6).move_to([2.8, -4.1, 0])
        self.play(FadeIn(lv), FadeIn(tm), run_time=0.4)
        self.en("multímetro")
        self.play(FadeIn(mm0), run_time=0.35)
        self.en("chasis")
        pr = CubicBezier(mm0.p("VΩ"), mm0.p("VΩ") + DOWN * 1.4, lv.p("chasis") + UP * 1.4, lv.p("chasis")).set_stroke("#D62828", 6)
        pn = CubicBezier(mm0.p("COM"), mm0.p("COM") + DOWN * 1.6, tm.p("tierra0") + UP * 1.6, tm.p("tierra0")).set_stroke("#151515", 6)
        pn2 = pn.copy().set_stroke("#8D949B", 9).set_z_index(-1)
        self.play(Create(pr), Create(pn2), Create(pn), run_time=0.6)
        self.en("120|ciento")
        mm1 = Pieza("mm_120", alto=4.4)
        self.poner(mm1, mm0)
        self.sfx("tic", -8)
        n1 = self.nota("120 V: hay fuga", Rr, [2.6, 3.0, 0], 26)
        self.play(FadeIn(n1, scale=1.2), run_time=0.3)
        self.en("desconecte|desconecta")
        n2 = self.nota("desconéctalo y no lo uses", Am, [-2.0, 3.0, 0], 22)
        self.play(FadeIn(n2), run_time=0.3)
        self.en("regla")
        self.play(*[FadeOut(m) for m in (mm1, lv, tm, pr, pn, pn2, n1, n2)], run_time=0.35)
        r1 = self.card("CHISPA DE UN INSTANTE", ["estática: un susto"], G, 7.8, 30).move_to([0, 1.2, 0])
        r2 = self.card("HORMIGUEO QUE SE REPITE", ["falla: desconecta y repara"], Rr, 7.8, 30).move_to([0, -1.3, 0])
        self.play(FadeIn(r1, shift=UP * 0.15), run_time=0.35)
        self.en("hormigueo")
        self.play(FadeIn(r2, shift=UP * 0.15), run_time=0.35)
        self.cerrar(r1, r2)
        self.quitar_chip()
        self.final("Estática: miles de voltios, milijoules · Fuga: 120 V que no se acaban")


